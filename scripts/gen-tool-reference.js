#!/usr/bin/env node
'use strict';

/**
 * Generates docs/tools.md from the MCP tool definitions in lib/mcp-server.js.
 *
 *   node scripts/gen-tool-reference.js           write docs/tools.md
 *   node scripts/gen-tool-reference.js --check   exit 1 when docs/tools.md is out of date
 *
 * test/tool-reference.test.js runs the same render and fails on drift, so a tool cannot be
 * added, renamed or re-described without the reference following.
 */

const fs = require('fs');
const path = require('path');
const { TOOLS } = require('../lib/mcp-server');

const OUT = path.join(__dirname, '..', 'docs', 'tools.md');

// When to reach for each tool. A tool without a line here fails the render on purpose.
const WHEN = {
  uiux_audit_run: 'You want the whole audit in one call. Start here.',
  uiux_scan_project: 'You only need to know the stack: framework, styling, component library, theme.',
  uiux_extract_colors: 'You want every color in the project, with where it is used.',
  uiux_extract_typography: 'You want the fonts, sizes, weights and line heights in use.',
  uiux_extract_spacing: 'You want the padding, margin and gap values in use.',
  uiux_check_contrast: 'You have a foreground and a background color and want the WCAG and APCA numbers.',
  uiux_score_dimension: 'You gathered data for one dimension yourself and want its score.',
  uiux_score_overall: 'You have per-dimension scores and want the weighted total.',
  uiux_generate_palette: 'You have a brand color and need a full palette, dark mode included.',
  uiux_generate_type_scale: 'You need a type scale from a base size and a ratio.',
  uiux_generate_spacing_scale: 'You need a spacing scale from a base unit.',
  uiux_generate_tokens: 'You need a complete token set: color, type, spacing, radius, shadow, motion.',
  uiux_knowledge_query: 'You want the reasoning behind a rule, from the bundled knowledge files.',
  uiux_laws_query: 'You want the definition and source of a named UX law.',
  uiux_audit_log: 'An agent found something by reading code and wants to record it.',
  uiux_audit_report: 'You want the findings recorded with uiux_audit_log as one report.',
};

function cell(text) {
  return String(text).replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
}

function typeOf(schema) {
  if (!schema) return 'any';
  if (schema.enum) return schema.enum.map(v => `\`${v}\``).join(' or ');
  if (schema.type === 'array') return `array of ${schema.items && schema.items.type ? schema.items.type : 'values'}`;
  return schema.type || 'any';
}

function render() {
  const missing = TOOLS.filter(t => !WHEN[t.name]).map(t => t.name);
  if (missing.length) throw new Error(`scripts/gen-tool-reference.js has no "when to use" line for: ${missing.join(', ')}`);
  const stale = Object.keys(WHEN).filter(n => !TOOLS.some(t => t.name === n));
  if (stale.length) throw new Error(`scripts/gen-tool-reference.js names tools that no longer exist: ${stale.join(', ')}`);

  const order = Object.keys(WHEN);
  const tools = TOOLS.slice().sort((a, b) => order.indexOf(a.name) - order.indexOf(b.name));
  const out = [];
  out.push('# MCP tool reference');
  out.push('');
  out.push('<!-- Generated by scripts/gen-tool-reference.js. Do not edit by hand: run `npm run docs:tools`. -->');
  out.push('');
  out.push(`The MCP server exposes ${TOOLS.length} tools over stdio. Start it with \`npx -y ui-ux-suite --mcp\`.`);
  out.push('Every tool is read-only over your source.');
  out.push('No tool calls the network, with one exception: `uiux_audit_run` in deep mode opens the `baseUrl` you pass.');
  out.push('');
  out.push('## Which tool do I use?');
  out.push('');
  out.push('| Tool | Use it when |');
  out.push('| --- | --- |');
  for (const t of tools) out.push(`| [\`${t.name}\`](#${t.name}) | ${cell(WHEN[t.name])} |`);
  out.push('');
  out.push('## Tools');
  for (const t of tools) {
    out.push('');
    out.push(`### ${t.name}`);
    out.push('');
    out.push(t.description.replace(/\s+/g, ' ').trim());
    const props = (t.inputSchema && t.inputSchema.properties) || {};
    const required = new Set((t.inputSchema && t.inputSchema.required) || []);
    const names = Object.keys(props);
    out.push('');
    if (names.length === 0) {
      out.push('Takes no argument.');
      continue;
    }
    out.push('| Argument | Type | Required | What it is |');
    out.push('| --- | --- | --- | --- |');
    for (const n of names) {
      out.push(`| \`${n}\` | ${cell(typeOf(props[n]))} | ${required.has(n) ? 'yes' : 'no'} | ${cell(props[n].description || '')} |`);
    }
  }
  out.push('');
  return out.join('\n');
}

module.exports = { render, OUT };

if (require.main === module) {
  const text = render();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== text) {
      console.error('docs/tools.md is out of date. Run: npm run docs:tools');
      process.exit(1);
    }
    console.log(`docs/tools.md is up to date (${TOOLS.length} tools).`);
  } else {
    fs.writeFileSync(OUT, text);
    console.log(`Wrote docs/tools.md (${TOOLS.length} tools).`);
  }
}
